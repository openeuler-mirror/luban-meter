"""Multi-turn conversation performance against an online chat service.

One sample is one whole session.  Its turns run strictly one after
another inside a single worker thread, because each turn's history
depends on the reply to the previous one.  Sessions run concurrently
under whichever request-level profile is selected, and the sample
thread count follows the effective request capacity, so at most one
request per session is in flight.

Assistant text is regenerated by the model under test and fed back as
history.  Dataset assistant turns delimit turns but are never replayed,
so the measured prefill cost reflects what this deployment actually
accumulates.  Dataset system messages are preserved; the command line
system prompt applies only when a record provides none.

``multi_max_turns`` is an upper bound, not a filter.  A session with
fewer usable turns runs to its natural end and keeps its own
``planned_turns``.  A turn that fails aborts its session: padding the
history with placeholder text would corrupt the prefill cost of every
later turn, so partial sessions keep their completed turns and mark the
rest as not started.  Reaching the request budget or duration limit
stops admission without extending it to finish sessions.
"""

from __future__ import annotations

import itertools
import random
import time
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from luban_meter.api import (
    GenerationPerformanceBenchmark,
    Parameter,
    benchmarks,
)
from luban_meter.benchmarking.benchmark_parameters import HTTP
from luban_meter.benchmarking.generation_performance import (
    generation_benchmarks,
)
from luban_meter.data import DatasetLoader
from luban_meter.data.projections import (
    extract_conversation,
    split_turns,
    summarize_turn_counts,
)
from luban_meter.log import get_logger
from luban_meter.runtime.http_client import create_http_client, http_settings
from luban_meter.runtime.request_params import (
    append_request_params,
    validate_request_params,
)
from luban_meter.runtime.request_scheduler import AdmissionStopped

from .common.lengths import assess_lengths
from .common.phase_timing import select_phase_metrics
from .common.reasoning_tokens import prepare_reasoning_counter
from .common.tokenization import LengthSampler, derived_seed, load_tokenizer

logger = get_logger(__name__)

# Poll interval for think-time sleeps so a stop request is honoured
# promptly instead of after the whole gap has elapsed.
_THINK_POLL_S = 0.05

# Abort reasons that strike after the turn's request was sent.  Such a
# turn already counts in the error-rate denominator, so it is reported
# separately from turns that were never started.
_SENT_FAILED_REASONS = frozenset(
    {"turn_failed", "reasoning_only", "no_output"}
)

CONVERSATION_PARAMETERS = {
    "multi_max_turns": Parameter(
        int, 8, minimum=1, matrix=True,
        help=(
            "upper bound on turns per session; shorter sessions are kept "
            "and end naturally rather than filtered out"
        ),
    ),
    "multi_num_sessions": Parameter(
        int, 100, minimum=1, matrix=True,
        help="sessions to run; each session is many model calls, not one",
    ),
    "multi_think_time": Parameter(
        float, 0.0, minimum=0.0, matrix=True,
        help="mean idle seconds between turns; 0 sends back to back",
    ),
    "multi_think_time_std": Parameter(
        float, 0.0, minimum=0.0,
        help="standard deviation of the idle gap between turns",
    ),
    "multi_system_prompt": Parameter(
        str, "",
        help=(
            "prepended only when the record provides no system message; "
            "dataset system content always wins and the choice is recorded"
        ),
    ),
    "multi_session_timeout": Parameter(
        float, None, minimum=0.001,
        help="wall-clock cap per session; exceeded sessions stop early",
    ),
    "multi_save_response_text": Parameter(
        bool, False,
        help=(
            "also persist the assembled messages array per session; each "
            "turn's generated_text is recorded either way"
        ),
    ),
}


@benchmarks.register("multi_turn_serving")
class MultiTurnServingBenchmark(GenerationPerformanceBenchmark):
    """Chat sessions whose turns accumulate real conversation history."""

    profile_modes = frozenset({"requests"})
    capabilities = frozenset({"client_stream_timing", "multi_turn_timing"})
    default_metrics = ("streaming_performance", "streaming_phase_timing")
    summary_fields = GenerationPerformanceBenchmark.summary_fields + (
        "multi_max_turns",
        "multi_num_sessions",
        "multi_think_time",
    )
    parameters = {
        **HTTP,
        **CONVERSATION_PARAMETERS,
        # Multi-turn history is a chat concept; completions has no roles.
        "endpoint": Parameter(
            str,
            "chat",
            choices=("chat",),
            help=HTTP["endpoint"].help,
        ),
        "profile": Parameter(str, "concurrent"),
        "data": Parameter(str, "sharegpt", choices=("sharegpt",)),
        "dataset_path": Parameter(str, "", path=True, required=True),
        "max_samples": Parameter(int, None, minimum=1),
        "shuffle": Parameter(bool, False),
        "repeat_data": Parameter(bool, False),
        "output_tokens": Parameter(int, 128, minimum=1, matrix=True),
        "output_tokens_std": Parameter(int, None, minimum=0),
        "output_tokens_min": Parameter(int, None, minimum=1),
        "output_tokens_max": Parameter(int, None, minimum=1),
        "stop": Parameter(list, [], item_type=str),
        "ignore_eos": Parameter(bool, True),
        "length_policy": Parameter(
            str, "observe", choices=("observe", "strict")
        ),
        "max_model_len": Parameter(int, None, minimum=1),
        "tokenizer": Parameter(str, ""),
        "thinking_metrics": Parameter(
            bool, False, help="enable thinking and content phase metrics",
        ),
        "data_seed": Parameter(int, None, minimum=0),
        "goodput": Parameter(list, [], item_type=str),
        "circuit_breaker": Parameter(float, None, minimum=0.001),
        "max_error_rate": Parameter(float, None, minimum=0.0, maximum=1.0),
    }

    @classmethod
    def select_metrics(cls, parameters):
        return select_phase_metrics(
            parameters, super().select_metrics(parameters),
        )

    @classmethod
    def validate(cls, parameters):
        http_settings(parameters)
        validate_request_params(parameters["request_params"])
        generation_benchmarks.thresholds(
            parameters["goodput"], ("ttft", "tpot", "e2el")
        )
        if parameters["multi_think_time_std"] and not parameters[
            "multi_think_time"
        ]:
            raise ValueError(
                "multi_think_time_std requires a positive multi_think_time"
            )
        # Still validates the output-length configuration itself, but no
        # "worst-case turns × max output" precheck: max turns is an upper
        # bound that shorter sessions never reach, natural EOS keeps
        # replies under the budget, and the per-turn real-history check
        # in evaluate() stops a session only when its actual context
        # would overflow.  Rejecting the worst case would turn away legal
        # short-session workloads.
        LengthSampler.from_parameters(parameters, "output")
        # A request budget below one full pass is legitimate: it admits
        # fewer calls and sessions stay partially complete, which the
        # facts record.  Rejecting it would force callers to guess the
        # per-session turn total that only the dataset determines.

    def prepare(self, context):
        self.p = context.parameters
        max_turns = self.p["multi_max_turns"]
        seed = (
            self.p["data_seed"]
            if self.p["data_seed"] is not None
            else self.p["seed"]
        )
        # max_samples limits candidate records and is applied by the
        # loader before turn truncation, so it can shrink the usable
        # pool; the resulting counts are recorded rather than implied.
        records = DatasetLoader(
            self.p["dataset_path"],
            format=self.p["data"],
            max_samples=self.p.get("max_samples"),
            shuffle=self.p["shuffle"],
            seed=seed,
        ).load()
        if not records:
            raise ValueError("dataset contains no conversations")
        cli_system = self.p["multi_system_prompt"]
        self.sessions = []
        # Structural validity is enforced whole-file by the ShareGPT
        # source adapter, so the only per-record rejection left is a
        # conversation with nothing to send.
        unusable = 0
        source_counts: list[int] = []
        system_source = {"dataset": 0, "cli": 0, "none": 0, "ignored_cli": 0}
        for index, record in enumerate(records):
            increments = split_turns(extract_conversation(record))
            source_counts.append(len(increments))
            if not increments:
                unusable += 1
                continue
            has_system = any(
                message["role"] == "system" for message in increments[0]
            )
            if has_system:
                system_source["dataset"] += 1
                if cli_system:
                    system_source["ignored_cli"] += 1
            elif cli_system:
                system_source["cli"] += 1
            else:
                system_source["none"] += 1
            identifier = record.get("id")
            self.sessions.append(
                {
                    # Source identity, for traceability only.  It must
                    # never index self.sessions, whose positions differ
                    # once records are filtered, shuffled or truncated.
                    "record_index": index,
                    "record_id": (
                        identifier
                        if isinstance(identifier, str) and identifier
                        else f"record-{index}"
                    ),
                    "turns": increments[:max_turns],
                    "available_turns": len(increments),
                    "planned_turns": min(len(increments), max_turns),
                    "has_system": has_system,
                }
            )
        if not self.sessions:
            summary = summarize_turn_counts(source_counts)
            raise ValueError(
                f"no usable conversation in {len(records)} records "
                f"({unusable} without any user turn).\n"
                f"数据集不含可用会话。该数据集轮次分布: "
                f"min={summary['min']} p50={summary['p50']} "
                f"p90={summary['p90']} max={summary['max']}"
            )
        self.system_source = system_source
        planned_total = sum(row["planned_turns"] for row in self.sessions)
        self.filter_facts = {
            "source_file": Path(self.p["dataset_path"]).name,
            "max_turns": max_turns,
            "source_total": len(records),
            "source_turn_distribution": summarize_turn_counts(source_counts),
            "usable": len(self.sessions),
            "usable_ratio": round(len(self.sessions) / len(records), 4),
            "unusable_no_user_turn": unusable,
            "truncated": sum(
                1
                for row in self.sessions
                if row["available_turns"] > max_turns
            ),
            "planned_turn_distribution": summarize_turn_counts(
                [row["planned_turns"] for row in self.sessions]
            ),
            # One model call per planned turn, so this is the request
            # total a full pass would admit without any other stop.
            "planned_requests_total": planned_total,
            "shuffle": self.p["shuffle"],
            "shuffle_seed": seed,
            "max_samples": self.p.get("max_samples"),
            "system_prompt_source": dict(system_source),
        }
        needed = self.p["multi_num_sessions"]
        if len(self.sessions) < needed and not self.p["repeat_data"]:
            raise ValueError(
                f"multi_num_sessions={needed} exceeds the "
                f"{len(self.sessions)} usable conversations in the dataset"
                f" ({unusable} without any user turn skipped).\n"
                f"数据集数量与参数不匹配。可选方案:\n"
                f"  1. 降低 --multi-num-sessions 至 "
                f"{len(self.sessions)} 以内\n"
                f"  2. 开启 --repeat-data 循环使用可用会话"
                + (
                    "\n  3. 取消或调大 --max-samples（它在轮次处理之前"
                    "截断候选记录，当前值 "
                    f"{self.p.get('max_samples')}）"
                    if self.p.get("max_samples")
                    else ""
                )
            )
        self.tokenizer = (
            load_tokenizer(self.p) if self.p["max_model_len"] else None
        )
        self.reasoning_token_counter = prepare_reasoning_counter(
            self.p, self.tokenizer,
        )
        self.outputs = LengthSampler.from_parameters(self.p, "output")
        self.seed = seed
        from .online_serving import ActiveRequestTracker

        self.tracker = ActiveRequestTracker()
        settings = http_settings(self.p)
        self.client = create_http_client(
            self.p["request_timeout"],
            max_connections=settings["max_connections"],
            keepalive_expiry=settings["keepalive_expiry"],
        )
        context.total_samples = self.p["multi_num_sessions"]

    def close(self):
        if getattr(self, "client", None) is not None:
            self.client.close()

    def samples(self, context):
        phase = context.phase
        pool = (
            itertools.cycle(range(len(self.sessions)))
            if self.p["repeat_data"]
            else iter(range(len(self.sessions)))
        )
        for index in range(self.p["multi_num_sessions"]):
            try:
                pool_index = next(pool)
            except StopIteration:
                logger.debug("Conversation sample pool exhausted")
                # The usable pool ran out.  repeat_data is the only way
                # to reuse it, so sessions are never silently padded.
                return
            session = self.sessions[pool_index]
            planned = session["planned_turns"]
            # Keep the yielded sample free of conversation text: it is
            # copied verbatim into the raw facts, and long sessions
            # would otherwise duplicate the dataset on disk.
            yield {
                "session_index": index,
                # Position in the filtered pool, used to look the session
                # up at execution time.  record_index identifies the
                # source record and is never an index into the pool.
                "pool_index": pool_index,
                "record_index": session["record_index"],
                "record_id": session["record_id"],
                "planned_turns": planned,
                "output_budgets": [
                    self.outputs.sample(
                        derived_seed(
                            self.seed, phase, index * planned + turn,
                            "output_length",
                        )
                    )
                    for turn in range(planned)
                ],
                "think_times": [
                    self._think_time(index, turn, phase)
                    for turn in range(planned - 1)
                ],
            }

    def _think_time(self, session, turn, phase) -> float:
        mean = self.p["multi_think_time"]
        if not mean:
            return 0.0
        std = self.p["multi_think_time_std"]
        rng = random.Random(
            derived_seed(self.seed, phase, session * 1024 + turn, "think_time")
        )
        if not std:
            return mean
        return max(0.0, rng.gauss(mean, std))

    def _initial_history(self, session) -> list[dict[str, str]]:
        """Start a session's history and resolve the system prompt source.

        A dataset system message stays where the record put it, inside
        the first turn.  The command line prompt is used only when the
        record has none, so neither source is silently discarded and the
        choice is visible in the case metadata.
        """
        if session["has_system"]:
            return []
        prompt = self.p["multi_system_prompt"]
        if not prompt:
            return []
        return [{"role": "system", "content": prompt}]

    def _context_overflow(self, history, budget) -> int | None:
        """Measure the prompt about to be sent against the model limit.

        Applied to the assembled history with the real chat template, so
        role order matches the request and a tokenizer that requires
        alternation cannot fail after the fact.  Returns the measured
        prompt length when the turn would not fit, otherwise None.
        """
        limit = self.p["max_model_len"]
        if self.tokenizer is None or not limit:
            return None
        tokens = self.tokenizer.apply_chat_template(
            history,
            tokenize=True,
            return_dict=False,
            add_generation_prompt=True,
        )
        return len(tokens) if len(tokens) + budget > limit else None

    def _payload(self, history, budget) -> dict[str, Any]:
        payload = {
            "model": self.p["model"],
            "max_tokens": budget,
            "temperature": self.p["temperature"],
            "seed": self.p["seed"],
            "stream": True,
            "stream_options": {"include_usage": True},
            "stop": self.p["stop"],
            "messages": list(history),
        }
        if self.p["ignore_eos"]:
            payload.update(min_tokens=budget, ignore_eos=True)
        return append_request_params(payload, self.p["request_params"])

    def _send_turn(self, ticket, payload, sample, turn, context):
        from .common.streaming import collect_chat_stream
        from .online_serving import execute_request

        record = execute_request(
            client=self.client,
            request_index=ticket.index,
            payload=payload,
            endpoint=self.p["endpoint"],
            service_url=self.p["base_url"],
            api_key=self.p["api_key"],
            timeout=self.p["request_timeout"],
            benchmark_start=context.scheduler.started,
            scheduled_time=ticket.scheduled,
            tracker=self.tracker,
            stream_collector=collect_chat_stream,
            thinking_metrics=self.p["thinking_metrics"],
            reasoning_token_counter=self.reasoning_token_counter,
        )
        record["lengths"] = assess_lengths(
            {"target_output_tokens": sample["output_budgets"][turn]},
            record.get("input_tokens"),
            record.get("output_tokens"),
            self.p,
        )
        return record

    def _session_expired(self, started) -> bool:
        limit = self.p["multi_session_timeout"]
        return limit is not None and time.perf_counter() - started >= limit

    def _think(self, context, seconds):
        if seconds <= 0:
            return
        deadline = time.perf_counter() + seconds
        while True:
            remaining = deadline - time.perf_counter()
            if remaining <= 0 or context.stopped():
                return
            time.sleep(min(remaining, _THINK_POLL_S))

    def evaluate(self, sample, context):
        planned = sample["planned_turns"]
        session = self.sessions[sample["pool_index"]]
        history = self._initial_history(session)
        started = time.perf_counter()
        completed = 0
        think_total = 0.0
        abort_reason = None
        overflow_tokens = None
        # A normal admission stop is caught here so the session summary
        # below stays recomputable: budget, duration and interrupt stops
        # leave completed facts and an explicit abort reason instead of
        # an empty sample. The incomplete marker is already set by
        # RunContext.request before the exception surfaces.
        for turn in range(planned):
            if self._session_expired(started):
                abort_reason = "session_timeout"
                break
            history.extend(session["turns"][turn])
            budget = sample["output_budgets"][turn]
            # Checked before sending: an over-limit turn is a workload
            # fact, not a service failure, and must not be recorded
            # as a request error.
            overflow_tokens = self._context_overflow(history, budget)
            if overflow_tokens is not None:
                abort_reason = "context_overflow"
                break
            try:
                record = context.request(
                    lambda ticket: self._send_turn(
                        ticket,
                        self._payload(history, budget),
                        sample,
                        turn,
                        context,
                    ),
                    metadata={
                        "turn_index": turn,
                        "session_turns": planned,
                    },
                )
            except AdmissionStopped as exc:
                # The turn never reached the service: it counts as not
                # started, never as a sent failure, and the scheduler's
                # reason (num_requests, max_duration, user_interrupt)
                # explains why the session stopped.
                logger.debug(
                    "Session %s admission stopped at turn %s: %s",
                    sample["session_index"], turn, exc,
                )
                abort_reason = str(exc) or "request budget"
                break
            if record.get("status") != "success":
                abort_reason = "turn_failed"
                break
            # A reasoning-only response is a valid performance
            # observation, but a session cannot continue without
            # assistant text to carry forward.  Record which of the
            # two happened instead of merging them.
            reply = record.get("generated_text")
            if not isinstance(reply, str) or not reply:
                abort_reason = (
                    "reasoning_only"
                    if record.get("reasoning_text")
                    else "no_output"
                )
                break
            completed += 1
            history.append({"role": "assistant", "content": reply})
            if turn + 1 < planned:
                gap = sample["think_times"][turn]
                self._think(context, gap)
                think_total += gap
        ended = time.perf_counter()
        sent_failed = 1 if abort_reason in _SENT_FAILED_REASONS else 0
        return {
            "status": "success" if completed == planned else "failed",
            "session_index": sample["session_index"],
            "record_id": sample["record_id"],
            "record_index": sample["record_index"],
            "planned_turns": planned,
            "completed_turns": completed,
            # A post-send abort already counts in the error-rate
            # denominator, so only the turns after it are "not started".
            "not_started_turns": planned - completed - sent_failed,
            "sent_failed_turns": sent_failed,
            "abort_reason": abort_reason,
            "context_overflow_tokens": overflow_tokens,
            "session_latency_ms": round((ended - started) * 1000, 3),
            "think_time_total_ms": round(think_total * 1000, 3),
            **(
                {"history": [dict(item) for item in history]}
                if self.p["multi_save_response_text"]
                else {}
            ),
        }

    def metadata(self, context):
        result = {
            "multi_max_turns": self.p["multi_max_turns"],
            "multi_num_sessions": self.p["multi_num_sessions"],
            "request_concurrency": context.scheduler.capacity,
            "available_sessions": len(self.sessions),
            "system_prompt_source": dict(self.system_source),
            "multi_save_response_text": self.p["multi_save_response_text"],
            # Assistant text is regenerated, never replayed from data.
            "history_source": "model_under_test",
        }
        slo = generation_benchmarks.thresholds(
            self.p["goodput"], ("ttft", "tpot", "e2el")
        )
        if slo:
            result["slo_config"] = {
                f"{name}_ms": value for name, value in slo.items()
            }
        result["dataset_filter"] = self.filter_facts
        return result

    def stop_after(self, facts):
        from .common.circuit_breaker import (
            case_p99_e2el_ms,
            check_stop_constraints,
        )

        requests = [
            record
            for record in facts["requests"]
            if isinstance(record, Mapping)
        ]
        # Latency percentiles use successful first turns only: later
        # turns carry a longer prefill, so the same threshold would mean
        # something else.
        first_turns = [
            record["response"]
            for record in requests
            if record.get("status") == "success"
            and isinstance(record.get("response"), Mapping)
            and record.get("scheduling", {}).get("turn_index") == 0
        ]
        threshold = self.p["circuit_breaker"]
        if threshold is not None:
            p99 = case_p99_e2el_ms({"requests": first_turns})
            if p99 is not None and p99 > threshold:
                return "circuit_breaker_exceeded"
        # The error rate denominator is every request that finished,
        # failed ones included.  Turns never admitted are absent from
        # the facts and so are not counted as service failures.
        return check_stop_constraints(
            {"requests": requests},
            max_duration=None,
            max_error_rate=self.p["max_error_rate"],
        )
